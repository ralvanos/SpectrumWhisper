class DeviceMatch {
  const DeviceMatch(this.category, this.tag);
  final String category;
  final String tag;
}

/// Longest broadcast-name match. The model is included only when the name contains it.
DeviceMatch? matchDeviceName(String ssid) {
  final folded = ssid.toLowerCase();
  if (folded.trim().isEmpty) return null;
  final named = _best(folded, _names, boundary: true);
  if (named != null && named.category != 'printer' && named.category != 'hotspot') {
    if (named.category == 'phone' && named.tag == 'Motorola' && _found(folded, 'motorola', true)) {
      final routed = _mixedRouter(folded);
      if (routed != null) return routed;
    }
    return named;
  }
  final vehicle = _best(
    folded,
    [for (final rule in _names) if (rule.category == 'vehicle') rule],
    boundary: true,
  );
  if (vehicle != null && (named == null || named.category == 'hotspot')) return vehicle;
  final styled = _defaultVehicleSsid(folded);
  if (styled != null && (named == null || named.category == 'hotspot')) return styled;
  if (named != null && named.category == 'hotspot') return named;
  final loose = _looseVehicle(folded);
  if (loose != null) return loose;
  final mixed = _mixedPrinter(folded);
  if (named == null || (mixed != null && named.tag == 'Printer')) {
    if (mixed != null) return mixed;
  } else if (named != null) {
    return named;
  }
  return _yamaha(folded) ?? _mixedRouter(folded);
}

/// Ford-style defaults: Hotspot plus an id, or PROJ plus an id, with no spaces.
DeviceMatch? _defaultVehicleSsid(String folded) {
  if (folded.contains(' ')) return null;
  final compact = folded.replaceAll(RegExp(r'[^a-z0-9]'), '');
  if (RegExp(r'^hotspot[a-z0-9]{2,16}$').hasMatch(compact)) {
    return const DeviceMatch('vehicle', 'Vehicle hotspot');
  }
  if (RegExp(r'^proj(?!ect)[a-z0-9]{2,16}$').hasMatch(compact)) {
    return const DeviceMatch('vehicle', 'Vehicle projection');
  }
  return null;
}

/// Toyota's default phrase. A known router brand in the same name keeps the router.
DeviceMatch? _looseVehicle(String folded) {
  const routerHints = [
    'netgear',
    'tp-link',
    'tplink',
    'asus',
    'linksys',
    'eero',
    'orbi',
    'arris',
    'google',
    'xfinity',
    'verizon',
  ];
  if (routerHints.any(folded.contains)) return null;
  if (folded.contains('wi-fi connect') || folded.contains('wifi connect')) {
    return const DeviceMatch('vehicle', 'Toyota');
  }
  return null;
}

DeviceMatch? _yamaha(String folded) {
  if (!_found(folded, 'yamaha', true)) return null;
  const hints = ['motor', 'motorcycle', 'atv', 'wolverine', 'grizzly', 'tenere', 'tracer', 'yxz', 'mt-07', 'mt-09', ' r1', ' r6'];
  if (hints.any(folded.contains)) return const DeviceMatch('vehicle', 'Yamaha Vehicle');
  return null;
}

/// Brands that also make phones, computers, or printers. A router tag is used
/// only when the name also looks like network gear.
DeviceMatch? _mixedRouter(String folded) {
  const brands = <List<String>>[
    ['apple', 'Apple Router'],
    ['acer', 'Acer Router'],
    ['asrock', 'ASRock'],
    ['dell', 'Dell Router'],
    ['google', 'Google Wifi'],
    ['intel', 'Intel'],
    ['motorola', 'Motorola'],
  ];
  const hints = ['router', 'wifi', 'wi-fi', 'gateway', 'modem', 'airport', 'access point'];
  if (!hints.any(folded.contains)) return null;
  for (final brand in brands) {
    if (_found(folded, brand[0], true)) return DeviceMatch('router', brand[1]);
  }
  return null;
}

/// Brands that also make phones, computers, or cameras. The tag says printer
/// only when the name also looks like a printer, so a phone is left alone.
DeviceMatch? _mixedPrinter(String folded) {
  const brands = <List<String>>[
    ['apple', 'Apple Printer'],
    ['dell', 'Dell Printer'],
    ['samsung', 'Samsung Printer'],
    ['panasonic', 'Panasonic Printer'],
    ['toshiba', 'Toshiba Printer'],
    ['fujitsu', 'Fujitsu Printer'],
    ['sharp', 'Sharp Printer'],
    ['kodak', 'Kodak Printer'],
    ['polaroid', 'Polaroid Printer'],
    ['citizen', 'Citizen Printer'],
    ['roland', 'Roland Printer'],
    ['seiko', 'Seiko Printer'],
    ['ibm', 'IBM Printer'],
  ];
  const hints = ['printer', 'print', 'laser', 'inkjet', 'mfp', 'copier', 'plotter', 'airprint', 'label'];
  final hinted = hints.any((hint) => folded.contains(hint));
  if (hinted) {
    for (final brand in brands) {
      if (_found(folded, brand[0], brand[0].length <= 4)) return DeviceMatch('printer', brand[1]);
    }
  }
  if (_found(folded, 'hp', true) || folded.contains('hewlett')) {
    return const DeviceMatch('printer', 'HP Printer');
  }
  return null;
}

/// Longest vendor-name match from the on-phone OUI table.
DeviceMatch? matchDeviceVendor(String maker) {
  final folded = maker.toLowerCase();
  if (folded.isEmpty || folded == 'private address' || folded == 'unknown maker') return null;
  return _best(folded, _vendors, boundary: false);
}

DeviceMatch? _best(String folded, List<_Rule> rules, {required bool boundary}) {
  _Rule? best;
  for (final rule in rules) {
    final text = rule.pattern;
    if (best != null && text.length < best.pattern.length) continue;
    final strict = _careful.contains(text) || (boundary && text.length <= 4);
    if (!_found(folded, text, strict)) continue;
    if (best == null || text.length > best.pattern.length) best = rule;
  }
  return best == null ? null : DeviceMatch(best.category, best.tag);
}

bool _found(String folded, String text, bool strict) {
  var start = 0;
  while (start < folded.length) {
    final at = folded.indexOf(text, start);
    if (at < 0) return false;
    final before = at == 0 || !_letter(folded.codeUnitAt(at - 1));
    final afterAt = at + text.length;
    final after = afterAt >= folded.length || !_letter(folded.codeUnitAt(afterAt));
    if (before && (!strict || after)) return true;
    start = at + 1;
  }
  return false;
}

bool _letter(int code) => (code >= 65 && code <= 90) || (code >= 97 && code <= 122);

